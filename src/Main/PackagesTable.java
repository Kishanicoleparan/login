    private void deletepackageActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deletepackageActionPerformed
       int row = table_package.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a package to delete!");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this package?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {
        try {
            Connection conn = connectDB();
            int id = Integer.parseInt(table_package.getValueAt(row, 0).toString());

            String sql = "DELETE FROM tbl_packages WHERE p_id = ?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, id);
            pst.executeUpdate();

            conn.close();

            JOptionPane.showMessageDialog(this, "Package deleted successfully!");
            displayPackage();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    }//GEN-LAST:event_deletepackageActionPerformed

